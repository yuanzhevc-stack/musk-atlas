import { chromium } from "playwright";
const URL = process.argv[2], SHOT = process.argv[3];
const b = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs=[], bad=[]; p.on("pageerror", e=>errs.push(e.message)); p.on("response", r=>{ if (r.status()>=400) bad.push(r.status()+" "+r.url()); });
await p.goto(URL, { waitUntil: "networkidle" });
console.log("canPlay h264:", await p.evaluate(() => document.createElement("video").canPlayType('video/mp4; codecs="avc1.4D401E, mp4a.40.2"')));
await p.fill('input[aria-label="搜索单词或短语"]', "look at");
await p.waitForSelector('[data-testid="hit"]');
console.log("hits:", await p.textContent('[data-testid="hit-count"]'));
await p.locator('[data-testid="hit"]').first().click();
await p.waitForSelector('[data-testid="clip"]');
const v = p.locator('[data-testid="clip"]');
console.log("src:", await v.getAttribute("src"));
await p.waitForTimeout(2500);
const st = await v.evaluate(el => ({ t: el.currentTime, dur: el.duration, paused: el.paused, err: el.error && el.error.code, rs: el.readyState }));
console.log("video state:", JSON.stringify(st));
await p.screenshot({ path: SHOT });
await p.keyboard.press("ArrowDown"); await p.waitForTimeout(1500);
console.log("after ↓:", await v.getAttribute("src"), await v.evaluate(el => el.currentTime.toFixed(2)));
console.log("errors", errs, "4xx", bad); await b.close();
